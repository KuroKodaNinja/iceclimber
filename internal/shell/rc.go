package shell

import "github.com/KuroKodaNinja/iceclimber/internal/remote"

// Layout under the install root.
const (
	dirName    = "shell"           // <root>/shell
	binName    = "bash"            // <root>/shell/bash
	rcName     = "bashrc"          // <root>/shell/bashrc
	histName   = ".bash_history"   // <root>/shell/.bash_history
)

// BinPath / RCPath are the sandbox paths for the installed bash and its rc file. They are
// exported so `iceclimber shell` can build its login command without re-deriving the layout.
func BinPath(root string) string { return root + "/" + dirName + "/" + binName }
func RCPath(root string) string  { return root + "/" + dirName + "/" + rcName }

// EnvPreamble returns a POSIX-sh snippet that sets up the "reasonable environment" for an
// interactive login into the sandbox: ICECLIMBER_HOME, popo/nana + the installed shell on
// PATH, every installed runtime's bin dir on PATH (installed runtimes are otherwise only
// reachable by absolute path), and the egress proxy/CA-trust env when serving in proxy mode.
// It is shared by the bash rc (below) and `iceclimber shell`'s no-bash / `-c` fallbacks so the
// login environment has ONE definition. root is baked in shell-quoted.
func EnvPreamble(root string) string {
	q := remote.ShellQuote(root)
	return "export ICECLIMBER_HOME=" + q + "\n" +
		`PATH="$ICECLIMBER_HOME/` + dirName + `:$ICECLIMBER_HOME:$PATH"` + "\n" +
		`for d in "$ICECLIMBER_HOME"/runtimes/*/*/bin; do [ -d "$d" ] && PATH="$d:$PATH"; done` + "\n" +
		`export PATH` + "\n" +
		`[ -f "$ICECLIMBER_HOME/egress-env.sh" ] && . "$ICECLIMBER_HOME/egress-env.sh"` + "\n"
}

// renderRC builds the bash rc dropped at <root>/shell/bashrc. It reuses EnvPreamble (which
// bakes in and exports ICECLIMBER_HOME, so the rc is self-contained even if bash is launched by
// hand) for the PATH/egress setup, then adds the bash-only niceties an interactive operator
// expects: persistent appended history under the iceclimber tree (not a possibly-unwritable
// $HOME), case-insensitive completion, and a prompt that says where you are.
func renderRC(root string) string {
	return "# iceclimber shell rc — generated by `iceclimber install shell`; do not edit.\n" +
		EnvPreamble(root) +
		`export HISTFILE="$ICECLIMBER_HOME/` + dirName + `/` + histName + `"` + "\n" +
		"export HISTSIZE=5000 HISTFILESIZE=10000\n" +
		"shopt -s histappend 2>/dev/null || true\n" +
		"bind 'set completion-ignore-case on' 2>/dev/null || true\n" +
		`PS1='[iceclimber \w]\$ '` + "\n"
}
