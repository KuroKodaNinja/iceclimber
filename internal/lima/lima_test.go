// TestSSHConfigField parses Hostname/User/IdentityFile out of a sample ssh.config the way
// Lima generates it — first match wins, quotes trimmed, case-insensitive key, missing key
// yields "". This is the detail extraction SSHDetails depends on; it mirrors the
// functional harness's sshConfigField, so the two stay in lockstep without a VM.
func TestSSHConfigField(t *testing.T) {
	dir := t.TempDir()
	sample := `# generated by lima
Host lima-iceclimber-dev
  Hostname 127.0.0.1
  User "bob"
  IdentityFile "/home/bob/.lima/_config/user"
  Port 60123
  IdentityFile /should/be/ignored/second
`
	if err := os.WriteFile(filepath.Join(dir, "ssh.config"), []byte(sample), 0o644); err != nil {
		t.Fatal(err)
	}

	tests := []struct {
		key, want string
	}{
		{"Hostname", "127.0.0.1"},
		{"hostname", "127.0.0.1"},                        // case-insensitive key
		{"User", "bob"},                                  // quotes trimmed
		{"IdentityFile", "/home/bob/.lima/_config/user"}, // first match wins
		{"Port", "60123"},
		{"Nonexistent", ""},
	}
	for _, tt := range tests {
		if got := sshConfigField(dir, tt.key); got != tt.want {
			t.Errorf("sshConfigField(%q) = %q, want %q", tt.key, got, tt.want)
		}
	}
}

// TestSSHConfigFieldMissingFile: no ssh.config in dir → "" for every key (never panics).
func TestSSHConfigFieldMissingFile(t *testing.T) {
	if got := sshConfigField(t.TempDir(), "Hostname"); got != "" {
		t.Errorf("sshConfigField on missing file = %q, want \"\"", got)
	}
}

// TestEmbeddedAssets: the template + air-gap script are embedded and non-empty, and carry
// the load-bearing markers the CLI/contract rely on (vz VM, the non-sudo agent user, the
// default-drop egress with no public destinations).
func TestEmbeddedAssets(t *testing.T) {
	tmpl := string(UbuntuTemplate)
	for _, want := range []string{"vmType: vz", "useradd", "agent"} {
		if !strings.Contains(tmpl, want) {
			t.Errorf("ubuntu.yaml missing %q", want)
		}
	}
	scr := string(AirgapScript)
	for _, want := range []string{"OUTPUT DROP", "--dport 53", "ESTABLISHED,RELATED"} {
		if !strings.Contains(scr, want) {
			t.Errorf("airgap.sh missing %q", want)
		}
	}
	// The iceclimber air-gap must NOT allow any Anthropic/public range (egress rides the
	// reverse tunnel only) — guard against copy-paste from the demo firewall.
	if strings.Contains(scr, "160.79.104") || strings.Contains(scr, "2607:6bc0") {
		t.Error("airgap.sh must not allow Anthropic public ranges; egress rides the SSH reverse tunnel")
	}
}
